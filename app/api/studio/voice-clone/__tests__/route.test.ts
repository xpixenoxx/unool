import { describe, it, expect, vi, beforeEach } from 'vitest';
import { NextRequest } from 'next/server';

const {
  mockGetCurrentAuth,
  mockRequireWorkspaceRole,
  mockFindProfileByWorkspace,
  mockFindConnectionsByWorkspace,
  mockCloneCreatorVoice,
} = vi.hoisted(() => ({
  mockGetCurrentAuth: vi.fn(),
  mockRequireWorkspaceRole: vi.fn(),
  mockFindProfileByWorkspace: vi.fn(),
  mockFindConnectionsByWorkspace: vi.fn(),
  mockCloneCreatorVoice: vi.fn(),
}));

vi.mock('@/lib/auth/server', () => ({
  getCurrentAuth: (req: unknown) => mockGetCurrentAuth(req),
}));

vi.mock('@/lib/auth/workspaceAccess', () => ({
  requireWorkspaceRole: (...args: unknown[]) => mockRequireWorkspaceRole(...args),
}));

vi.mock('@/lib/repositories/supabase/SupabaseProfileRepository', () => ({
  SupabaseProfileRepository: class {
    findByWorkspaceId = mockFindProfileByWorkspace;
  },
}));

vi.mock('@/lib/repositories/supabase/SupabasePlatformRepository', () => ({
  SupabasePlatformRepository: class {
    findByWorkspaceId = mockFindConnectionsByWorkspace;
  },
}));

vi.mock('@/lib/ai/voiceCloning', async () => {
  const actual = await vi.importActual<typeof import('@/lib/ai/voiceCloning')>(
    '@/lib/ai/voiceCloning'
  );
  return {
    ...actual,
    cloneCreatorVoiceForWorkspace: (...args: unknown[]) => mockCloneCreatorVoice(...args),
  };
});

vi.mock('@/lib/logger', () => ({
  logger: {
    info: vi.fn(),
    warn: vi.fn(),
    error: vi.fn(),
    debug: vi.fn(),
  },
}));

import { GET, POST } from '../route';
import { resetVoiceCloneRateLimits } from '@/lib/ai/voiceCloning';

describe('/api/studio/voice-clone route handler', () => {
  beforeEach(() => {
    vi.clearAllMocks();
    resetVoiceCloneRateLimits();
    mockRequireWorkspaceRole.mockResolvedValue({ allowed: true });
  });

  it('GET returns 401 when unauthenticated', async () => {
    mockGetCurrentAuth.mockResolvedValue(null);
    const req = new NextRequest('http://localhost:3000/api/studio/voice-clone');
    const res = await GET(req);
    expect(res.status).toBe(401);
  });

  it('GET returns current voiceFingerprint and connected voice channels', async () => {
    mockGetCurrentAuth.mockResolvedValue({ userId: 'u1', workspaceId: 'ws1' });
    mockFindProfileByWorkspace.mockResolvedValue({
      id: 'p1',
      studioProfile: {
        role: 'Founder',
        voiceFingerprint: {
          version: 1,
          postsAnalyzed: 15,
          voiceSummary: 'Punchy founder voice',
        },
      },
    });
    mockFindConnectionsByWorkspace.mockResolvedValue([
      { id: 'c1', platform: 'linkedin', username: 'hemanth', displayName: 'Hemanth', status: 'connected' },
      { id: 'c2', platform: 'youtube', username: 'yt', status: 'connected' },
    ]);

    const req = new NextRequest('http://localhost:3000/api/studio/voice-clone');
    const res = await GET(req);
    expect(res.status).toBe(200);
    const json = await res.json();
    expect(json.hasVoiceFingerprint).toBe(true);
    expect(json.connectedVoiceChannels).toHaveLength(1);
    expect(json.connectedVoiceChannels[0].platform).toBe('linkedin');
  });

  it('POST returns 403 when caller has viewer role', async () => {
    mockGetCurrentAuth.mockResolvedValue({ userId: 'u-viewer', workspaceId: 'ws1' });
    mockRequireWorkspaceRole.mockResolvedValue({ allowed: false });

    const req = new NextRequest('http://localhost:3000/api/studio/voice-clone', {
      method: 'POST',
      body: JSON.stringify({ platform: 'linkedin' }),
    });
    const res = await POST(req);
    expect(res.status).toBe(403);
  });

  it('POST returns 400 when no voice-capable channel is connected and no samplePosts provided', async () => {
    mockGetCurrentAuth.mockResolvedValue({ userId: 'u1', workspaceId: 'ws-empty' });
    mockFindConnectionsByWorkspace.mockResolvedValue([]);

    const req = new NextRequest('http://localhost:3000/api/studio/voice-clone', {
      method: 'POST',
      body: JSON.stringify({}),
    });
    const res = await POST(req);
    expect(res.status).toBe(400);
    const json = await res.json();
    expect(json.code).toBe('NO_VOICE_SOURCE');
  });

  it('POST clones voice successfully when connected channel exists', async () => {
    mockGetCurrentAuth.mockResolvedValue({ userId: 'u1', workspaceId: 'ws-active' });
    mockFindConnectionsByWorkspace.mockResolvedValue([
      { id: 'conn-1', platform: 'instagram', username: 'creator', status: 'connected' },
    ]);
    mockCloneCreatorVoice.mockResolvedValue({
      profile: {
        role: 'Creator',
        doing: 'Visual storytelling',
        audience: 'Designers',
        tone: 'Witty',
        style: 'Short & punchy',
        interests: ['Photography'],
      },
      voiceFingerprint: {
        version: 1,
        autoGenerated: true,
        postsAnalyzed: 20,
        sourcePlatforms: ['instagram'],
        confidence: 'high',
        voiceSummary: 'Visual, witty creator voice.',
      },
      postsAnalyzed: 20,
      sourcePlatforms: ['instagram'],
      confidence: 'high',
      skippedManualOverwrite: false,
      durationMs: 1840,
    });

    const req = new NextRequest('http://localhost:3000/api/studio/voice-clone', {
      method: 'POST',
      body: JSON.stringify({ platform: 'instagram', connectionId: 'conn-1' }),
    });
    const res = await POST(req);
    expect(res.status).toBe(200);
    const json = await res.json();
    expect(json.success).toBe(true);
    expect(json.postsAnalyzed).toBe(20);
    expect(json.confidence).toBe('high');
    expect(mockCloneCreatorVoice).toHaveBeenCalledWith(
      expect.objectContaining({
        workspaceId: 'ws-active',
        userId: 'u1',
        preferredPlatform: 'instagram',
        preferredConnectionId: 'conn-1',
      })
    );
  });
});
